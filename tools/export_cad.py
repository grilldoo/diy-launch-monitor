"""Generate CAD inputs from the code's geometry and render the printable files.

    python tools/export_cad.py            # writes cad/generated/*, cad/stl/*.stl, cad/club_markers.svg

Requires the openscad CLI. Rerun after changing the ball pattern, rig geometry or
club marker layout, so the printed parts always match what the solver assumes.
"""

import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from launchmonitor.dots import PATTERN_FILE, load_pattern  # noqa: E402
from launchmonitor.rig import four_camera_rig  # noqa: E402
from launchmonitor.sim import FACE_MARKERS_UV  # noqa: E402

import json  # noqa: E402

CAD = ROOT / "cad"
GEN = CAD / "generated"
STL = CAD / "stl"
HEADER = "// GENERATED by tools/export_cad.py - do not edit.\n"


def write_ball_pattern(gen=GEN):
    p = load_pattern()
    # Pattern y (seam normal) becomes jig +Z. (x, y, z) -> (x, -z, y) is a proper rotation,
    # never a mirror: a mirrored jig would mark the wrong pattern.
    jig = np.column_stack([p[:, 0], -p[:, 2], p[:, 1]])
    assert np.isclose(np.linalg.det(np.array([[1, 0, 0], [0, 0, -1], [0, 1, 0]])), 1)
    dot_d = json.loads(PATTERN_FILE.read_text())["dot_diameter_mm"]
    rows = ",\n".join(f"  [{x:.6f}, {y:.6f}, {z:.6f}]" for x, y, z in jig)
    (gen / "ball_pattern.scad").write_text(f"{HEADER}dot_diameter_mm = {dot_d};\ndots = [\n{rows}\n];\n")


def write_rig_angles(gen=GEN):
    rig = four_camera_rig()
    pairs = [rig.ball_cams, rig.club_cams]
    out = []
    for pair in pairs:
        a, b = pair
        right = b.center - a.center
        right[1] = 0
        right /= np.linalg.norm(right)
        up = np.array([0.0, 1.0, 0.0])
        fwd = np.cross(up, right)  # (right, fwd, up) right-handed, matching SCAD (X, Y, Z)
        for cam in pair:
            f = cam.R[2]  # camera forward in world
            fx, fy, fz = f @ right, f @ fwd, f @ up
            yaw = np.degrees(np.arctan2(-fx, fy))
            pitch = np.degrees(np.arcsin(fz))
            out.append((cam.name, yaw, pitch))
    rows = ",\n".join(f'  ["{n}", {y:.2f}, {p:.2f}]' for n, y, p in out)
    baseline = np.linalg.norm(rig.ball_cams[1].center - rig.ball_cams[0].center) * 1000
    (gen / "rig_angles.scad").write_text(
        f"{HEADER}// [name, yaw_deg (+ = counter-clockwise seen from above), pitch_deg (+ = up)]\n"
        f"// Mount the two cameras of a pair {baseline:.0f} mm apart (lens centre to lens centre).\n"
        f"cams = [\n{rows}\n];\n"
    )
    return out


def write_club_marker_sheet(cols=4, rows=3, dot_d=3.0, margin=4.0):
    uv = FACE_MARKERS_UV * 1000  # mm; u toward toe, v up the face
    lo, hi = uv.min(axis=0) - margin, uv.max(axis=0) + margin
    w, h = hi - lo
    pitch_x, pitch_y = w + 8, h + 14
    W, H = cols * pitch_x + 20, rows * pitch_y + 40
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.1f}mm" height="{H:.1f}mm" viewBox="0 0 {W:.1f} {H:.1f}">',
        '<rect width="100%" height="100%" fill="white"/>',
        '<text x="10" y="8" font-family="sans-serif" font-size="4">Club face markers - print at 100% on matte white '
        "sticker paper; check the 50 mm bar. Place near the toe, arrow toward toe, face grooves level.</text>",
        '<line x1="10" y1="14" x2="60" y2="14" stroke="black" stroke-width="0.6"/>',
        '<text x="62" y="15.5" font-family="sans-serif" font-size="3.5">50 mm</text>',
    ]
    for r in range(rows):
        for c in range(cols):
            ox, oy = 10 + c * pitch_x, 22 + r * pitch_y
            parts.append(f'<rect x="{ox:.2f}" y="{oy:.2f}" width="{w:.2f}" height="{h:.2f}" rx="2" fill="none" stroke="#bbb" stroke-width="0.2"/>')
            for u, v in uv:
                # SVG y grows downward: v (up the face) maps to -y
                parts.append(f'<circle cx="{ox + u - lo[0]:.3f}" cy="{oy + hi[1] - v:.3f}" r="{dot_d / 2}" fill="black"/>')
            ay = oy + h + 4
            parts.append(f'<line x1="{ox + 2:.2f}" y1="{ay:.2f}" x2="{ox + w - 4:.2f}" y2="{ay:.2f}" stroke="#666" stroke-width="0.4"/>')
            parts.append(f'<polygon points="{ox + w - 4:.2f},{ay - 1.2:.2f} {ox + w - 1:.2f},{ay:.2f} {ox + w - 4:.2f},{ay + 1.2:.2f}" fill="#666"/>')
            parts.append(f'<text x="{ox + 2:.2f}" y="{ay + 4:.2f}" font-family="sans-serif" font-size="2.5" fill="#666">TOE</text>')
    parts.append("</svg>")
    (CAD / "club_markers.svg").write_text("\n".join(parts) + "\n")


def openscad(src: str, out: str, **params):
    args = ["openscad", "-q", "--export-format", "binstl", "-o", str(STL / out)]
    for k, v in params.items():
        args += ["-D", f'{k}={json.dumps(v)}']
    subprocess.run(args + [str(CAD / src)], check=True)
    print("wrote", STL / out)


def main():
    GEN.mkdir(exist_ok=True)
    STL.mkdir(exist_ok=True)
    write_ball_pattern()
    cams = write_rig_angles()
    write_club_marker_sheet()
    openscad("ball_jig.scad", "ball_jig_both_halves.stl", part="both")
    for i, (name, yaw, pitch) in enumerate(cams):
        openscad("camera_mount.scad", f"camera_mount_{name}.stl", cam=i)
        print(f"  {name}: yaw {yaw:+.1f} deg, pitch {pitch:+.1f} deg")


if __name__ == "__main__":
    main()
