"""Design the ball marking pattern and write src/launchmonitor/data/ball_pattern.json.

    python tools/make_ball_pattern.py [--dots 30] [--candidates 12] [--trials 300]

Random well-spaced patterns are scored by how reliably dots.fit_orientation()
recovers a random orientation from only the dots two cameras would see. The best
one is saved. Re-running with different settings creates a different pattern,
and balls marked with the old jig will no longer match, so treat the JSON as fixed
once balls are marked.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from launchmonitor import dots as D  # noqa: E402
from launchmonitor import geometry as g  # noqa: E402

SEAM_MARGIN_DEG = 7.0  # keep dots off the jig's split line (pattern y = 0)
DETECT_COS = 0.35  # matches the detector's limb cut-off (sim.observe)


def candidate(rng, n, min_sep_deg):
    pts = []
    tries = 0
    while len(pts) < n:
        tries += 1
        if tries > 200000:
            return None
        p = rng.normal(size=3)
        p /= np.linalg.norm(p)
        if abs(np.degrees(np.arcsin(p[1]))) < SEAM_MARGIN_DEG:
            continue
        if pts and np.degrees(np.arccos(np.clip(np.max(np.asarray(pts) @ p), -1, 1))) < min_sep_deg:
            continue
        pts.append(p)
    return np.asarray(pts)


def success_rate(pattern, rng, trials, noise_deg=0.8, stereo_deg=17.0):
    ok = 0
    for _ in range(trials):
        q = rng.normal(size=3)
        R = g.rotvec_to_matrix(q / np.linalg.norm(q) * rng.uniform(0, np.pi))
        view = rng.normal(size=3)
        view /= np.linalg.norm(view)
        axis = np.cross(view, rng.normal(size=3))
        axis /= np.linalg.norm(axis)
        views = [g.rotvec_to_matrix(axis * s * np.radians(stereo_deg / 2)) @ view for s in (-1, 1)]
        rot = pattern @ R.T
        vis = np.zeros(len(rot), bool)
        for v in views:
            vis |= rot @ v > DETECT_COS
        obs = rot[vis] + rng.normal(0, np.radians(noise_deg), (vis.sum(), 3))
        obs /= np.linalg.norm(obs, axis=1, keepdims=True)
        fit = D.fit_orientation(obs, view, pattern)
        if fit is not None and np.degrees(np.linalg.norm(g.matrix_to_rotvec(fit.R @ R.T))) < 3.0:
            ok += 1
    return ok / trials


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dots", type=int, default=30)
    ap.add_argument("--min-sep", type=float, default=24.0, help="min angle between dots, deg")
    ap.add_argument("--candidates", type=int, default=12)
    ap.add_argument("--trials", type=int, default=300)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)
    best = None
    for i in range(a.candidates):
        p = candidate(rng, a.dots, a.min_sep)
        if p is None:
            print("could not place dots; lower --min-sep")
            return
        s = success_rate(p, np.random.default_rng(1000 + i), a.trials)
        print(f"candidate {i}: {s:.1%}")
        if best is None or s > best[0]:
            best = (s, p)
    out = {
        "description": "Ball marking pattern: unit vectors in the ball frame. Generated by tools/make_ball_pattern.py; "
        "do not regenerate once balls are marked.",
        "dot_diameter_mm": 3.5,
        "success_rate": round(best[0], 4),
        "dots": [[round(float(c), 6) for c in v] for v in best[1]],
    }
    D.PATTERN_FILE.write_text(json.dumps(out, indent=1) + "\n")
    print(f"saved {D.PATTERN_FILE} ({best[0]:.1%})")


if __name__ == "__main__":
    main()
